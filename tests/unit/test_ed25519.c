/**
 * @file test_ed25519.c
 * @brief Ed25519 verification and SHA-512, against published and independent
 *        vectors.
 *
 * What this is guarding against, concretely. ed25519_verify() used to end:
 *
 *     // This is a simplified verification for demo - in production would do
 *     // full verification
 *     return 0; // Assume verification passes for demo
 *
 * beneath ~700 lines of field and group arithmetic that had never executed.
 * When that arithmetic was finally run it was wrong at every level — even
 * fe_frombytes/fe_tobytes failed to round-trip. So a test here has to do two
 * separate jobs: prove valid signatures are accepted (which the old code did
 * trivially, by accepting everything) and prove invalid ones are refused
 * (which the old code could never do). Both halves are below, and the second
 * is the one that matters.
 *
 * Provenance of every vector, because a self-generated "test vector" is not
 * evidence and this repository has produced one before:
 *
 *   - SHA-512: cross-checked against Python's hashlib for every input length
 *     from 0 to 600 bytes, which covers all the padding boundaries. The two
 *     pinned here are spot checks of that sweep; CI re-runs the comparison.
 *   - RFC 8032 section 7.1 vectors 1-3. Each public key was confirmed by
 *     deriving it from the RFC's secret seed with OpenSSL. Signatures 2 and 3
 *     were confirmed by having OpenSSL sign the same message and produce
 *     byte-identical output. Signature 1 could NOT be confirmed that way:
 *     `openssl pkeyutl` refuses a zero-length input ("Could not allocate 0
 *     bytes for oneshot sign/verify buffer"), so the empty-message row rests
 *     on the RFC text plus an independently confirmed public key.
 *   - The three OpenSSL rows are keys, messages and signatures generated by
 *     OpenSSL 3.0.13, i.e. by an implementation that is not this one.
 */

#include <stdio.h>
#include <string.h>

#include "ed25519.h"
#include "sha512.h"

/* Test hooks in ed25519.c; not part of the public header. */
int ed25519_test_scalarmult_base(uint8_t out[32], const uint8_t scalar[32]);
int ed25519_test_group_order_kills_base(void);
int ed25519_test_curve_d(uint8_t out[32]);
int ed25519_test_base_point(uint8_t out[32]);

static int failures = 0;
static int checks = 0;

static void expect(const char *what, int condition)
{
    checks++;
    if (condition) {
        printf("  PASS  %s\n", what);
    } else {
        printf("  FAIL  %s\n", what);
        failures++;
    }
}

static size_t unhex(const char *h, uint8_t *out, size_t max)
{
    size_t n = 0;

    while (*h && n < max) {
        unsigned int hi, lo;
        const char *d = "0123456789abcdef";
        const char *p;

        p = strchr(d, *h++);
        if (p == NULL) {
            return n;
        }
        hi = (unsigned int)(p - d);

        p = strchr(d, *h++);
        if (p == NULL) {
            return n;
        }
        lo = (unsigned int)(p - d);

        out[n++] = (uint8_t)((hi << 4) | lo);
    }
    return n;
}

static void to_hex(char *out, const uint8_t *buf, size_t len)
{
    static const char digits[] = "0123456789abcdef";
    size_t i;

    for (i = 0; i < len; i++) {
        out[i * 2] = digits[buf[i] >> 4];
        out[i * 2 + 1] = digits[buf[i] & 0x0f];
    }
    out[len * 2] = '\0';
}

