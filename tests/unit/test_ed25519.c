/* RFC 8032 §7.1 TEST 3: two bytes 0xaf 0x82 */
static const uint8_t v3_pk[32] = {
    0xfc, 0x51, 0xcd, 0x8e, 0x62, 0x18, 0xa1, 0xa3, 0x8d, 0xa4, 0x7e, 0xd0,
    0x02, 0x30, 0xf0, 0x58, 0x08, 0x16, 0xed, 0x13, 0xba, 0x33, 0x03, 0xac,
    0x5d, 0xeb, 0x91, 0x15, 0x48, 0x90, 0x80, 0x25
};
static const uint8_t v3_msg[2] = { 0xaf, 0x82 };
static const uint8_t v3_sig[64] = {
    0x62, 0x91, 0xd6, 0x57, 0xde, 0xec, 0x24, 0x02, 0x48, 0x27, 0xe6, 0x9c,
    0x3a, 0xbe, 0x01, 0xa3, 0x0c, 0xe5, 0x48, 0xa2, 0x84, 0x74, 0x3a, 0x44,
    0x5e, 0x36, 0x80, 0xd7, 0xdb, 0x5a, 0xc3, 0xac, 0x18, 0xff, 0x9b, 0x53,
    0x8d, 0x16, 0xf2, 0x90, 0xae, 0x67, 0xf7, 0x60, 0x98, 0x4d, 0xc6, 0x59,
    0x4a, 0x7c, 0x15, 0xe9, 0x71, 0x6e, 0xd2, 0x8d, 0xc0, 0x27, 0xbe, 0xce,
    0xea, 0x1e, 0xc4, 0x0a
};

static int failures = 0;

static void expect(const char *what, int condition)
{
    printf("  %s  %s\n", condition ? "PASS" : "FAIL", what);
    if (!condition) {
        failures++;
    }
}

int main(void)
{
    static const ed25519_vector_t vectors[] = {
        { "RFC 8032 TEST 1 (empty message)", v1_pk, NULL, 0, v1_sig },
        { "RFC 8032 TEST 2 (1 byte)",        v2_pk, v2_msg, 1, v2_sig },
        { "RFC 8032 TEST 3 (2 bytes)",       v3_pk, v3_msg, 2, v3_sig },
    };
    size_t i;
    uint8_t broken_sig[64];
    uint8_t broken_msg[2];
    uint8_t other_key[32];

    for (i = 0; i < sizeof(vectors) / sizeof(vectors[0]); i++) {
        expect(vectors[i].name,
               ed25519_verify(vectors[i].sig, vectors[i].msg,
                              vectors[i].msg_len, vectors[i].pk) == 0);
    }

    /* Negatives: every one of these used to be accepted when verification
     * was `return 0`. */
    memcpy(broken_sig, v1_sig, sizeof(broken_sig));
    broken_sig[0] ^= 0x01;
    expect("tampered signature rejected (TEST 1, byte 0 flipped)",
           ed25519_verify(broken_sig, NULL, 0, v1_pk) != 0);

    memcpy(broken_sig, v3_sig, sizeof(broken_sig));
    broken_sig[63] ^= 0x80;
    expect("tampered signature rejected (TEST 3, last byte flipped)",
           ed25519_verify(broken_sig, v3_msg, sizeof(v3_msg), v3_pk) != 0);

    memcpy(broken_msg, v3_msg, sizeof(broken_msg));
    broken_msg[0] ^= 0x01;
    expect("tampered message rejected (TEST 3, message bit flipped)",
           ed25519_verify(v3_sig, broken_msg, sizeof(broken_msg), v3_pk) != 0);

    memcpy(other_key, v3_pk, sizeof(other_key));
    other_key[0] ^= 0x01;
    expect("wrong public key rejected (TEST 3 sig under a different key)",
           ed25519_verify(v3_sig, v3_msg, sizeof(v3_msg), other_key) != 0);

    printf("\n%d failures\n", failures);
    return failures == 0 ? 0 : 1;
}
