static void test_valid_signatures(void)
{
    unsigned n;

    for (n = 0; n < sizeof(valid_vectors) / sizeof(valid_vectors[0]); n++) {
        const struct vector *v = &valid_vectors[n];
        uint8_t pk[32], sig[64], msg[64];
        size_t msg_len;

        unhex(v->public_key, pk, sizeof(pk));
        unhex(v->signature, sig, sizeof(sig));
        msg_len = unhex(v->message, msg, sizeof(msg));

        expect(v->name, ed25519_verify(sig, msg, msg_len, pk) == 0);
    }
}

static void test_rejections(void)
{
    /* Work from a known-good vector and break one thing at a time. */
    const struct vector *v = &valid_vectors[3];
    uint8_t pk[32], sig[64], msg[64];
    size_t msg_len;

    unhex(v->public_key, pk, sizeof(pk));
    unhex(v->signature, sig, sizeof(sig));
    msg_len = unhex(v->message, msg, sizeof(msg));

    {
        uint8_t bad[64];
        memcpy(bad, sig, sizeof(bad));
        bad[0] ^= 0x01;
        expect("flipped bit in R rejected",
               ed25519_verify(bad, msg, msg_len, pk) != 0);
    }

    {
        uint8_t bad[64];
        memcpy(bad, sig, sizeof(bad));
        bad[32] ^= 0x01;
        expect("flipped bit in S rejected",
               ed25519_verify(bad, msg, msg_len, pk) != 0);
    }

    {
        uint8_t bad[64];
        memcpy(bad, msg, msg_len);
        bad[0] ^= 0x01;
        expect("flipped bit in the message rejected",
               ed25519_verify(sig, bad, msg_len, pk) != 0);
    }

    {
        uint8_t bad[32];
        memcpy(bad, pk, sizeof(bad));
        bad[0] ^= 0x01;
        expect("wrong public key rejected",
               ed25519_verify(sig, msg, msg_len, bad) != 0);
    }

    expect("truncated message rejected",
           msg_len == 0 || ed25519_verify(sig, msg, msg_len - 1, pk) != 0);

    /* A signature from a different key over a different message. */
    {
        uint8_t other_pk[32], other_sig[64];
        unhex(valid_vectors[4].public_key, other_pk, sizeof(other_pk));
        unhex(valid_vectors[4].signature, other_sig, sizeof(other_sig));
        expect("signature from another key rejected",
               ed25519_verify(other_sig, msg, msg_len, pk) != 0);
    }

    /* All zeroes. This is the specific input the old placeholder accepted,
     * and the one a caller supplies when it has nothing at all. */
    {
        uint8_t zpk[32], zsig[64], zmsg[32];
        memset(zpk, 0, sizeof(zpk));
        memset(zsig, 0, sizeof(zsig));
        memset(zmsg, 0, sizeof(zmsg));
        expect("all-zero signature and key rejected",
               ed25519_verify(zsig, zmsg, sizeof(zmsg), zpk) != 0);
    }

    expect("NULL signature rejected",
           ed25519_verify(NULL, msg, msg_len, pk) != 0);
    expect("NULL public key rejected",
           ed25519_verify(sig, msg, msg_len, NULL) != 0);
}

static void test_malleability(void)
{
    /* S + L verifies under the same equation as S, because the scalar only
     * matters modulo L. Accepting it means one signed message has many valid
     * signatures — which breaks any caller that treats a signature as a
     * unique identifier, and is what RFC 8032 section 8.4 requires rejecting.
     * The check is S < L, so add L to S and confirm the result is refused. */
    const struct vector *v = &valid_vectors[3];
    uint8_t pk[32], sig[64], msg[64], mauled[64];
    size_t msg_len;
    static const uint8_t L[32] = {
        0xed, 0xd3, 0xf5, 0x5c, 0x1a, 0x63, 0x12, 0x58,
        0xd6, 0x9c, 0xf7, 0xa2, 0xde, 0xf9, 0xde, 0x14,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10
    };
    unsigned int carry = 0;
    int i;

    unhex(v->public_key, pk, sizeof(pk));
    unhex(v->signature, sig, sizeof(sig));
    msg_len = unhex(v->message, msg, sizeof(msg));

    memcpy(mauled, sig, sizeof(mauled));
    for (i = 0; i < 32; i++) {
        unsigned int cur = (unsigned int)mauled[32 + i] + L[i] + carry;
        mauled[32 + i] = (uint8_t)cur;
        carry = cur >> 8;
    }

    expect("S + L rejected (signature malleability)",
           ed25519_verify(mauled, msg, msg_len, pk) != 0);

    /* Sanity: the unmodified signature still verifies, so the check above is
     * rejecting the mauling rather than something incidental. */
    expect("original signature still verifies",
           ed25519_verify(sig, msg, msg_len, pk) == 0);
}

static void test_scalarmult(void)
{
    uint8_t scalar[32];
    uint8_t out[32], base[32];

    /* [1]B == B, and [0]B is the identity, whose encoding is y=1. */
    memset(scalar, 0, sizeof(scalar));
    scalar[0] = 1;
    expect("scalarmult runs", ed25519_test_scalarmult_base(out, scalar) == 0);
    ed25519_test_base_point(base);
    expect("[1]B == B", memcmp(out, base, 32) == 0);

    memset(scalar, 0, sizeof(scalar));
    ed25519_test_scalarmult_base(out, scalar);
    {
        uint8_t identity[32];
        memset(identity, 0, sizeof(identity));
        identity[0] = 1;
        expect("[0]B is the identity", memcmp(out, identity, 32) == 0);
    }
}

int main(void)
{
    printf("Ed25519 and SHA-512 tests\n");

    test_sha512();
    test_curve_constants();
    test_valid_signatures();
    test_rejections();
    test_malleability();
    test_scalarmult();

    printf("\n%d checks, %d failures\n", checks, failures);
    return failures == 0 ? 0 : 1;
}
