static void test_sha512(void)
{
    uint8_t d[SHA512_DIGEST_SIZE];
    char hex[2 * SHA512_DIGEST_SIZE + 1];
    uint8_t big[600];
    size_t i;

    sha512(d, (const uint8_t *)"", 0);
    to_hex(hex, d, sizeof(d));
    expect("SHA-512(empty)",
           strcmp(hex, "cf83e1357eefb8bdf1542850d66d8007d620e4050b5715dc83"
                       "f4a921d36ce9ce47d0d13c5d85f2b0ff8318d2877eec2f63b93"
                       "1bd47417a81a538327af927da3e") == 0);

    sha512(d, (const uint8_t *)"abc", 3);
    to_hex(hex, d, sizeof(d));
    expect("SHA-512(\"abc\")",
           strcmp(hex, "ddaf35a193617abacc417349ae20413112e6fa4e89a97ea20a9"
                       "eeee64b55d39a2192992a274fc1a836ba3c23a3feebbd454d44"
                       "23643ce80e2a9ac94fa54ca49f") == 0);

    /* Streaming in awkward pieces must equal the one-shot result. A padding
     * bug shows up here and nowhere else. */
    for (i = 0; i < sizeof(big); i++) {
        big[i] = (uint8_t)(i * 7 + 11);
    }
    {
        uint8_t one_shot[SHA512_DIGEST_SIZE];
        uint8_t streamed[SHA512_DIGEST_SIZE];
        sha512_ctx_t ctx;
        size_t off = 0;
        size_t chunk = 1;

        sha512(one_shot, big, sizeof(big));

        sha512_init(&ctx);
        while (off < sizeof(big)) {
            size_t take = (chunk < sizeof(big) - off) ? chunk : sizeof(big) - off;
            sha512_update(&ctx, big + off, take);
            off += take;
            chunk = (chunk * 3 + 1) % 200 + 1;
        }
        sha512_final(&ctx, streamed);

        expect("SHA-512 streaming matches one-shot",
               memcmp(one_shot, streamed, sizeof(one_shot)) == 0);
    }

    /* Exactly one block, and the two lengths that force a second padding
     * block, are where a length-counter bug lives. */
    {
        uint8_t a[SHA512_DIGEST_SIZE], b[SHA512_DIGEST_SIZE];
        size_t lengths[] = { 111, 112, 113, 127, 128, 129, 239, 240 };
        unsigned n;
        int all_differ = 1;

        for (n = 0; n < sizeof(lengths) / sizeof(lengths[0]) - 1; n++) {
            sha512(a, big, lengths[n]);
            sha512(b, big, lengths[n + 1]);
            if (memcmp(a, b, sizeof(a)) == 0) {
                all_differ = 0;
            }
        }
        expect("SHA-512 distinguishes lengths across block boundaries",
               all_differ);
    }
}

