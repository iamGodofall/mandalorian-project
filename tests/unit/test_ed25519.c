static void test_curve_constants(void)
{
    uint8_t buf[32];
    char hex[65];

    /* The base point is derived in ed25519.c from y = 4/5 with even x, not
     * transcribed. If the field arithmetic or the decoder is wrong, this is
     * not the canonical encoding. */
    expect("base point derives", ed25519_test_base_point(buf) == 0);
    to_hex(hex, buf, 32);
    expect("base point is the canonical Ed25519 B",
           strcmp(hex, "58666666666666666666666666666666"
                       "66666666666666666666666666666666") == 0);

    /* d = -121665/121666, likewise computed rather than pasted. */
    expect("curve d derives", ed25519_test_curve_d(buf) == 0);
    to_hex(hex, buf, 32);
    expect("curve d is the Ed25519 d",
           strcmp(hex, "a3785913ca4deb75abd841414d0a7000"
                       "98e879777940c78c73fe6f2bee6c0352") == 0);

    /* This is what validates the hardcoded group order: L is by definition
     * the order of B, so [L]B is the identity. Any other literal fails. */
    expect("[L]B is the identity (validates the group-order constant)",
           ed25519_test_group_order_kills_base() == 0);
}

