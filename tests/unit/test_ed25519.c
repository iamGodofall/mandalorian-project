/*
 * test_ed25519.c — RFC 8032 §7.1 test vectors for the vendored TweetNaCl
 * Ed25519 verification, plus tamper negatives.
 *
 * This is the gate the project's own rules demand for crypto: a real
 * implementation must come with published test vectors run in CI, the way
 * SHA3 does. Vectors transcribed from RFC 8032 (January 2017), §7.1.
 */
#include <stdio.h>
#include <string.h>

#include "verified_boot.h"

typedef struct {
    const char *name;
    const uint8_t *pk;
    const uint8_t *msg;
    size_t msg_len;
    const uint8_t *sig;
} ed25519_vector_t;

